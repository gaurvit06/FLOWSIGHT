"""Generate a model card for the served model -> reports/MODEL_CARD.md

    python scripts/model_card.py

Everything numeric is read from the saved model metadata, so the card always matches the
model the API is serving. Rerun after every training run.
"""

from __future__ import annotations

import json

import pandas as pd
from _common import write_report

from nids.config import load_config, models_dir, resolve
from nids.models.registry import best_name, list_models, load_metadata


def main() -> None:
    root = models_dir()
    meta = load_metadata(best_name(root), root)
    m, cfg = meta["metrics"], meta["config"]
    anomaly_path = root / "anomaly" / "anomaly.json"
    anomaly = json.loads(anomaly_path.read_text("utf-8")) if anomaly_path.exists() else None
    project_cfg = load_config()
    thresholds = project_cfg["thresholds"]

    per_class = pd.DataFrame(m["per_class"]).T[["precision", "recall", "f1-score", "support"]]
    per_class["support"] = per_class["support"].astype(int)
    comparison = pd.DataFrame({
        x["name"]: {"val macro-F1": x["metrics"].get("val_macro_f1"),
                    "test macro-F1": x["metrics"]["macro_f1"],
                    "test FPR": x["metrics"]["false_positive_rate"],
                    "ms / flow": x["metrics"]["latency_ms_per_flow"]}
        for x in list_models(root)}).T
    split = meta.get("split_rows", {})
    synthetic = (resolve(project_cfg["data"]["raw_dir"]) / "sample_synthetic.csv").exists()

    md = [
        f"# Model card: FlowSight `{meta['name']}`", "",
        (f"Trained {meta['trained_at'][:19].replace('T', ' ')} UTC. Generated by "
        "`scripts/model_card.py` from the saved model metadata."), "",
    ]
    if synthetic:
        md += [("> ⚠️ **Trained on the synthetic sample.** None of these numbers mean "
               "anything. Fetch CIC-IDS2017 and retrain first."), ""]
    md += [
        "## Intended use",
        "- Classify network **flows** (CICFlowMeter features) as "
        + ", ".join(meta["classes"]) + ", and flag flows unlike any benign traffic as "
        "`Unknown-Anomaly`.",
        ("- Decision support for a human analyst: every alert carries a plain-English "
        "explanation, a severity and an incident grouping."),
        "- **Not** an inline firewall/IPS: it never blocks traffic.", "",
        "## Out of scope",
        "- Encrypted payload inspection (only flow statistics are used).",
        ("- Networks very different from the training data without retraining (see the drift "
        "monitor and the cross-dataset report)."), "",
        "## Training data",
        ("CIC-IDS2017 (see `reports/DATASET.md`). Identifiers (IPs, source port, flow ID, "
        "timestamp) are removed; duplicates removed before splitting."),
        (f"Stratified split: train {split.get('train', '?'):,} / validation "
        f"{split.get('validation', '?'):,} / test {split.get('test', '?'):,} flows "
        f"(seed {cfg['seed']}). The model was **chosen on validation** and evaluated "
        "**once** on test."), "",
        "## Model",
        (f"- Pipeline: StandardScaler → top-{cfg['features']['k']} feature selection "
         f"(`{cfg['features']['method']}`) → {meta['name']}"),
        f"- Selected features: {', '.join(meta['selected_features'])}", "",
        "## Performance (held-out test set)",
        (f"- Macro-F1 **{m['macro_f1']:.4f}** · accuracy {m['accuracy']:.4f} · "
        f"ROC-AUC (OvR) {m['roc_auc_ovr'] or float('nan'):.4f}"),
        f"- False positive rate (benign flagged as attack): {m['false_positive_rate']:.4%}",
        f"- Latency: {m['latency_ms_per_flow']:.2f} ms per single flow", "",
        per_class.round(4).to_markdown(), "",
        "### All models", "", comparison.round(4).to_markdown(), "",
    ]
    if anomaly:
        a = anomaly["metrics"]
        rec = a.get("missed_attacks_recovered")
        min_conf = project_cfg.get("anomaly", {}).get("min_benign_confidence", 0)
        md += ["## Unknown-attack rule",
               (f"A flow the classifier calls Benign becomes `Unknown-Anomaly` if the anomaly "
                f"detector fires **or** the classifier is less than {min_conf:.0%} sure."), "",
               "| test set | value |", "|---|---|",
               f"| attacks the classifier called Benign | {a.get('classifier_missed_attacks', '?')} |",
               f"| … recovered by the rule | {'n/a' if rec is None else f'{rec:.1%}'} |",
               (f"| benign flows turned into alerts by the rule | "
               f"{a.get('rule_benign_false_alarm_rate', float('nan')):.2%} |"),
               f"| anomaly detector alone: attacks flagged | {a['attack_flag_rate']:.2%} |",
               f"| anomaly detector alone: benign flagged | {a['benign_false_alarm_rate']:.2%} |",
               "",
               ("The benign-only Isolation Forest contributes little on CIC-IDS2017: most attacks "
                "look normal flow-by-flow (DECISIONS.md D17). For attacks the model has never "
                "seen, see `reports/zero_day.md`."), ""]
    md += [
        "## Quality gate",
        (f"CI fails if macro-F1 < {thresholds['macro_f1']} or any attack class's recall < "
        f"{thresholds['attack_recall']} (`tests/test_model_quality.py`)."), "",
        "## Limitations & risks",
        ("- CIC-IDS2017 is a 2017 lab capture: attack tools, traffic mix and the "
        "feature extractor version all shape what the model learns."),
        ("- Some classes may be recognised mostly by destination port (see "
        "`reports/shap_global.md`); a real attacker can change ports."),
        ("- Near-perfect test scores within one dataset do **not** imply the same on other "
        "networks; check `reports/cross_dataset.md`."),
        "- Adversaries who know the features can shape traffic to evade detection.",
        "- SHAP values show what the model relied on, not proof of malicious intent.",
    ]
    write_report("MODEL_CARD", "\n".join(md))


if __name__ == "__main__":
    main()
